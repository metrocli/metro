const SHAPE_BY_ID = new Map(SHAPES.map((shape) => [shape.id, shape]));

function listShapes() {
  return SHAPES.map((shape) => ({
    id: shape.id,
    title: shape.title,
    family: shape.family,
    maturity: shape.maturity,
    supportedModes: [...shape.supportedModes],
  }));
}

function getShape(id) {
  return SHAPE_BY_ID.get(id) || null;
}

function explainShape(id) {
  const shape = getShape(id);
  if (!shape) return null;
  return {
    schemaVersion: 'metro.shape.explain.v1',
    ...shape,
  };
}


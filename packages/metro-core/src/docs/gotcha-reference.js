function cloneList(values) {
  return values ? [...values] : [];
}

function annotateGotcha(gotcha) {
  const ruleIds = cloneList(gotcha.ruleIds);
  const missingRuleIds = ruleIds.filter((ruleId) => !RULES[ruleId]);
  const rules = ruleIds
    .filter((ruleId) => RULES[ruleId])
    .map((ruleId) => ({ id: ruleId, ...RULES[ruleId] }));

  return {
    ...gotcha,
    ruleIds,
    plannedRuleIds: cloneList(gotcha.plannedRuleIds),
    commandIds: cloneList(gotcha.commandIds),
    sources: cloneList(gotcha.sources),
    rules,
    missingRuleIds,
  };
}

function countBy(values, getKey) {
  return values.reduce((counts, value) => {
    const key = getKey(value);
    counts[key] = (counts[key] || 0) + 1;
    return counts;
  }, {});
}

function gotchaReference() {
  const gotchas = GOTCHA_COVERAGE.map(annotateGotcha);
  const coveredCount = gotchas.filter((gotcha) => gotcha.coverageStatus === 'covered').length;

  return {
    schemaVersion: 'metro.docs.gotcha-reference.v1',
    generatedFrom: 'metronome-cli/src/docs/gotcha-reference.js',
    sourceRegister: 'docs/metronome-cli/GOTCHAS.md',
    rulesGeneratedFrom: 'metronome-cli/src/validators/rules.js',
    sectionNavigation: GOTCHA_REFERENCE_SECTION_NAVIGATION.map((section) => ({ ...section })),
    summary: {
      gotchaCount: gotchas.length,
      coveredCount,
      partialCount: gotchas.filter((gotcha) => gotcha.coverageStatus === 'partial').length,
      openQuestionCount: gotchas.filter((gotcha) => gotcha.coverageStatus === 'open-question').length,
      coverageStatusCounts: countBy(gotchas, (gotcha) => gotcha.coverageStatus),
      categoryCounts: countBy(gotchas, (gotcha) => gotcha.category),
    },
    gotchas,
  };
}

